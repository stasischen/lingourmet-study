/** Deterministic, read-only dictionary lookup. No I/O, identity minting, or locale fallback. */
/** @typedef {{type:'dictionary-cluster',language:string,clusterKey:string,lemma:string,pos:string}} ClusterRef */
/** @typedef {{type:'dictionary-entry',cluster:ClusterRef,entryId:string}} EntryRef */
/** @typedef {{type:'dictionary-sense',entry:EntryRef,senseId:string}} SenseRef */
const text=v=>typeof v==='string'&&v.trim().length>0;
const fail=message=>{throw new TypeError(message);};
const own=(o,k)=>Object.prototype.hasOwnProperty.call(o,k);
function shape(o,keys){if(!o||typeof o!=='object'||Array.isArray(o)||Object.keys(o).some(k=>!keys.includes(k)))fail('Not a clean dictionary projection');}
const clone=v=>JSON.parse(JSON.stringify(v));
function freeze(v){if(v&&typeof v==='object'){Object.values(v).forEach(freeze);Object.freeze(v);}return v;}
export function clusterRef(language,lemma,pos){
 if(!text(language)||!text(lemma)||!text(pos)||/[\s:]/u.test(language)||/[\s:]/u.test(pos))fail('Invalid cluster components');
 return freeze({type:'dictionary-cluster',language,clusterKey:`${language}:${pos}:${lemma}`,lemma,pos});
}
export function entryRef(cluster,entryId){
 if(cluster?.type!=='dictionary-cluster'||!text(entryId)||!entryId.startsWith(`lingo-entry:${cluster.language}:`)||/[\s]/u.test(entryId)||!entryId.slice(`lingo-entry:${cluster.language}:`.length))fail('Expected Lingo-owned entry identity');
 const opaque=entryId.slice(`lingo-entry:${cluster.language}:`.length);if(!/^[A-Za-z0-9_-]+$/u.test(opaque)||/^h[0-9]+(?:s[0-9]+)?$/iu.test(opaque))fail('Entry order is not identity');
 return freeze({type:'dictionary-entry',cluster:clone(cluster),entryId});
}
export function senseRef(entry,senseId){
 if(entry?.type!=='dictionary-entry'||!text(senseId)||/[\s.:#]/u.test(senseId)||/^h\d/iu.test(senseId))fail('Expected entry-local sense identity');
 return freeze({type:'dictionary-sense',entry:clone(entry),senseId});
}
const result=(status,reason,extra={})=>freeze({status,reason,showAffordance:false,...extra});
/**
 * index is an explicit clean published projection, or an unavailable projection.
 * publication is input admission metadata, not permission generated by this module.
 * Semantic/rights/publication review MUST precede construction of a published input.
 */
export function createDictionaryResolver({index,allowCandidate=false}={}){
 if(index?.format==='lingourmet.dictionary-preview.v1')return createPreviewResolver(index,allowCandidate);
 shape(index,['format','availability','snapshot','clusters']);
 if(!index||index.format!=='lingourmet.dictionary-lookup.v1'||!['published','unavailable'].includes(index.availability)||!text(index.snapshot))fail('Invalid dictionary projection');
 const saved=clone(index),clusters=new Map(),atoms=new Map(),entryIds=new Set();
 if(!Array.isArray(saved.clusters))fail('Missing clusters');
 if(saved.availability==='unavailable'&&saved.clusters.length)fail('Unavailable input cannot carry learner entries');
 for(const c of saved.clusters){
  shape(c,['language','clusterKey','lemma','pos','atomIds','entries']);
  const ref=clusterRef(c.language,c.lemma,c.pos);
  if(c.clusterKey!==ref.clusterKey||clusters.has(c.clusterKey)||!Array.isArray(c.entries)||!c.entries.length)fail('Invalid or duplicate cluster');
  const atomList=c.atomIds??[];if(!Array.isArray(atomList)||new Set(atomList).size!==atomList.length||atomList.some(x=>!text(x)))fail('Invalid atom aliases');
  for(const e of c.entries){
   shape(e,['entryId','senses']);
   const er=entryRef(ref,e.entryId);if(entryIds.has(e.entryId))fail('Duplicate entry identity');entryIds.add(e.entryId);
   if(!Array.isArray(e.senses)||!e.senses.length)fail('Missing senses');const seen=new Set();
   for(const s of e.senses){shape(s,['senseId','definitions']);senseRef(er,s.senseId);if(seen.has(s.senseId))fail('Duplicate local sense');seen.add(s.senseId);
    if(!s.definitions||typeof s.definitions!=='object'||Array.isArray(s.definitions)||Object.values(s.definitions).some(v=>!text(v)))fail('Invalid learner definitions');
   }
  }
  clusters.set(c.clusterKey,c);
  for(const atom of atomList){const key=JSON.stringify([c.language,atom]);const list=atoms.get(key)??[];list.push(c);atoms.set(key,list);}
 }
 freeze(saved);
 function lookup(query={}){
  if(!query||typeof query!=='object'||Array.isArray(query))return result('missing','query-incomplete');
  const {language,atomId,lemma,pos,locale,senseSelector}=query;
  if(!text(language)||!text(locale))return result('missing','query-incomplete');
  if(saved.availability!=='published')return result('unavailable','published-index-unavailable');
  let matches=[];
  if(text(atomId)){
   matches=atoms.get(JSON.stringify([language,atomId]))??[];
   if(text(lemma))matches=matches.filter(c=>c.lemma===lemma);
   if(text(pos))matches=matches.filter(c=>c.pos===pos);
  }else if(text(lemma)&&text(pos)){
   let key;try{key=clusterRef(language,lemma,pos).clusterKey;}catch{return result('missing','query-invalid');}
   const c=clusters.get(key);if(c)matches=[c];
  }else return result('missing','exact-identity-required');
  if(!matches.length)return result('missing','identity-not-found');
  if(matches.length>1)return result('ambiguous','identity-ambiguous');
  const c=matches[0],cr=clusterRef(c.language,c.lemma,c.pos);
  if(senseSelector&&(!text(senseSelector.entryId)||!text(senseSelector.senseId)))return result('missing','selector-incomplete');
  const entries=[];
  for(const e of c.entries){
   shape(e,['entryId','senses']);
   if(senseSelector&&e.entryId!==senseSelector.entryId)continue;
   const er=entryRef(cr,e.entryId),senses=e.senses.filter(s=>!senseSelector||s.senseId===senseSelector.senseId);
   if(!senses.length)continue;
   // A partially localized cluster cannot silently omit branches and pretend they do not exist.
   if(senses.some(s=>!own(s.definitions,locale)))return result('missing','translation-not-available');
   entries.push({ref:er,lemma:c.lemma,pos:c.pos,senses:senses.map(s=>({ref:senseRef(er,s.senseId),definition:s.definitions[locale]}))});
  }
  if(!entries.length)return result('missing','selector-not-found');
  return result('resolved',null,{showAffordance:true,level:senseSelector?'sense':'entry',locale,entries});
 }
 return Object.freeze({lookup});
}
/** UI-only projection: IDs, provenance, diagnostics and status never become learner copy.
 * Preview lemma audio is an explicit authored target; definitions are never scanned for speech.
 */
export function learnerDictionaryView(value){
 if(value?.status!=='resolved'||value.showAffordance!==true)return null;
 return freeze({locale:value.locale,entries:value.entries.map(e=>({lemma:e.lemma,pos:e.pos,definitions:e.senses.map(s=>s.definition),...(e.pronunciation?{pronunciation:clone(e.pronunciation)}:{})}))});
}

/** An explicitly enabled local candidate view, distinct from canonical published lookup. */
function createPreviewResolver(index,enabled){
 shape(index,['format','availability','snapshot','entries']);
 if(index.availability!=='candidate'||!text(index.snapshot)||!Array.isArray(index.entries))fail('Invalid preview projection');
 const saved=clone(index),keys=new Set();
 for(const e of saved.entries){
  shape(e,['key','language','lemma','pos','status','pronunciation','definitions']);
  shape(e.pronunciation,['text','speech','lang']);if(e.pronunciation.text!==e.lemma||!text(e.pronunciation.speech)||e.pronunciation.lang!=='ja-JP')fail('Invalid authored preview pronunciation');
  if(!/^lp-[0-9a-f]{16}$/u.test(e.key)||keys.has(e.key)||e.status!=='candidate'||![e.language,e.lemma,e.pos].every(text))fail('Invalid preview entry');keys.add(e.key);
  if(!e.definitions||typeof e.definitions!=='object'||Array.isArray(e.definitions)||Object.values(e.definitions).some(v=>!text(v)))fail('Invalid preview definitions');
 }
 freeze(saved);
 return Object.freeze({lookup(query={}){
  if(enabled!==true)return result('unavailable','candidate-preview-not-enabled');
  if(!query||typeof query!=='object')return result('missing','query-incomplete');
  const {language,lemma,pos,locale,atomId,senseSelector}=query;
  if(![language,lemma,pos,locale].every(text))return result('missing','exact-identity-required');
  // A legacy row locator is private; do not treat a source atom or sense as a new canonical ref.
  if(atomId!==undefined)return result('missing','preview-does-not-resolve-canonical-atom');
  if(senseSelector!==undefined)return result('missing','preview-has-no-canonical-sense-selector');
  const matches=saved.entries.filter(e=>e.language===language&&e.lemma===lemma&&e.pos===pos);
  if(!matches.length)return result('missing','identity-not-found');
  if(matches.length>1)return result('ambiguous','identity-ambiguous');
  const e=matches[0];if(!own(e.definitions,locale))return result('missing','translation-not-available');
  return result('resolved',null,{showAffordance:true,level:'entry',locale,referenceTier:'legacy-candidate',entries:[{ref:{type:'dictionary-preview-entry',key:e.key},lemma:e.lemma,pos:e.pos,pronunciation:e.pronunciation,senses:[{definition:e.definitions[locale]}]}]});
 }});
}
